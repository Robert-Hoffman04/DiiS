#!/usr/bin/env python3
"""res/Wii_homebrew_cursors generic pointer + shadow -> source/cursor_tex.h.
Native pixels (no resampling): both images are cropped to their combined content box
and padded to a multiple of 4; RGB5A3 4x4 tiles. The pack puts the hotspot at the
image centre (48,48), moved here by the crop. Drawn one texel per 640x480 canvas pixel."""
from PIL import Image
D = "res/Wii_homebrew_cursors/images/"
imgs = {"CursorData": Image.open(D + "generic_point.png").convert("RGBA"),
        "CursorShadowData": Image.open(D + "shadow_point.png").convert("RGBA")}
boxes = [im.getchannel("A").getbbox() for im in imgs.values()]
x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
W, H = (x1 - x0 + 3) & ~3, (y1 - y0 + 3) & ~3

def c(r, g, b, a):
    if a >= 0xE0:
        return 0x8000 | (r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)
    return (a >> 5) << 12 | (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4)

with open("source/cursor_tex.h", "w") as f:
    f.write("// Generated by tools/cursor/mkcursor.py from res/Wii_homebrew_cursors. Do not edit.\n")
    f.write("// RGB5A3, 4x4 tiled; one texel per 640x480 canvas pixel.\n#pragma once\n")
    f.write(f"#define CURSOR_TEX_W {W}\n#define CURSOR_TEX_H {H}\n")
    f.write(f"#define CURSOR_HOT_X {48 - x0}\n#define CURSOR_HOT_Y {48 - y0}\n")
    for name, im in imgs.items():
        out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        out.paste(im.crop((x0, y0, x1, y1)), (0, 0))
        px = out.load()
        vals = [c(*px[tx + x, ty + y]) for ty in range(0, H, 4) for tx in range(0, W, 4)
                for y in range(4) for x in range(4)]
        f.write(f"static u16 {name}[CURSOR_TEX_W * CURSOR_TEX_H] __attribute__((aligned(32))) = {{\n")
        for i in range(0, len(vals), 8):
            f.write("\t" + ", ".join(f"0x{v:04X}" for v in vals[i:i + 8]) + ",\n")
        f.write("};\n")
