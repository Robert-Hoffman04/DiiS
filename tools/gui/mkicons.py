#!/usr/bin/env python3
"""Generic 32x32 library icons (games without their own icon) -> source/gui/gui_icons.h.
Pixel art drawn here (no source image), hard edges so it stays clean drawn 2x with a
nearest filter. Row-major RGB5A3, the same layout as LibGame::icon, so the GUI uploads
them through the same path. Run from the repo root:  python3 tools/gui/mkicons.py [--png]"""
import sys
from PIL import Image, ImageDraw

OUTLINE = (40, 44, 52, 255)


def ds():
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # Two halves of an open DS, hinge between them.
    d.rounded_rectangle((4, 1, 27, 15), 3, fill=(200, 205, 214, 255), outline=OUTLINE)
    d.rounded_rectangle((4, 16, 27, 30), 3, fill=(200, 205, 214, 255), outline=OUTLINE)
    d.rectangle((6, 15, 25, 16), fill=(120, 126, 138, 255))
    # Screens.
    d.rectangle((9, 4, 22, 12), fill=(64, 150, 220, 255), outline=(30, 60, 100, 255))
    d.rectangle((10, 5, 13, 6), fill=(150, 205, 245, 255))
    d.rectangle((9, 19, 22, 27), fill=(64, 150, 220, 255), outline=(30, 60, 100, 255))
    d.rectangle((10, 20, 13, 21), fill=(150, 205, 245, 255))
    # D-pad and buttons on the lower half.
    d.rectangle((6, 22, 6, 24), fill=OUTLINE)
    d.rectangle((5, 23, 7, 23), fill=OUTLINE)
    d.point((25, 22), fill=OUTLINE)
    d.point((25, 24), fill=OUTLINE)
    return im


def gba():
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    body = (98, 82, 168, 255)
    d.rounded_rectangle((1, 8, 30, 25), 6, fill=body, outline=OUTLINE)
    # Screen bezel and screen.
    d.rectangle((9, 10, 22, 21), fill=(52, 52, 60, 255))
    d.rectangle((10, 11, 21, 19), fill=(150, 200, 120, 255))
    d.rectangle((11, 12, 14, 13), fill=(200, 235, 170, 255))
    # D-pad.
    d.rectangle((4, 13, 6, 19), fill=OUTLINE)
    d.rectangle((3, 15, 7, 17), fill=OUTLINE)
    # A / B.
    d.ellipse((24, 13, 27, 16), fill=(220, 70, 90, 255), outline=OUTLINE)
    d.ellipse((21, 17, 24, 20), fill=(220, 70, 90, 255), outline=OUTLINE)
    # Shoulder buttons.
    d.rectangle((4, 7, 9, 8), fill=OUTLINE)
    d.rectangle((22, 7, 27, 8), fill=OUTLINE)
    return im


def c(r, g, b, a):
    if a >= 0xE0:
        return 0x8000 | (r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)
    return (a >> 5) << 12 | (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4)


icons = {"GuiIconGenericDs": ds(), "GuiIconGenericGba": gba()}
with open("source/gui/gui_icons.h", "w") as f:
    f.write("// Generated by tools/gui/mkicons.py. Do not edit.\n")
    f.write("// Generic 32x32 DS / GBA library icons, row-major RGB5A3 (same layout as LibGame::icon).\n")
    f.write("#pragma once\n")
    for name, im in icons.items():
        if "--png" in sys.argv:
            im.resize((256, 256), Image.NEAREST).save(f"{name}.png")
        px = im.load()
        vals = [c(*px[x, y]) for y in range(32) for x in range(32)]
        f.write(f"static const u16 {name}[32 * 32] = {{\n")
        for i in range(0, len(vals), 8):
            f.write("\t" + ", ".join(f"0x{v:04X}" for v in vals[i:i + 8]) + ",\n")
        f.write("};\n")
